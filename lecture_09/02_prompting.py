# Часть 3. Chain-of-thought
# ---------------------------------------------------------------------------
# Сравним два промпта на задачах в несколько действий:
# "сразу назови число" и "сначала рассуждай по шагам".

PUZZLES = [
    ("У Маши 3 коробки по 12 карандашей. 8 карандашей она отдала брату, "
     "а потом купила еще 2 коробки по 6. Сколько карандашей у Маши?", 40),
    ("В аудитории 5 рядов по 6 парт. За каждой партой 2 места, но 7 мест пустуют. "
     "Сколько студентов в аудитории?", 53),
    ("Модель обучается 4 эпохи. В одной эпохе 250 шагов, один шаг занимает 2 секунды. "
     "Сколько секунд длится все обучение?", 2000),
    ("У кота 4 лапы, у курицы 2. Во дворе 3 кота и 5 куриц. Сколько всего лап во дворе?", 22),
    ("Поезд выехал в 9 часов и ехал 3 часа, затем стоял 1 час и ехал еще 2 часа. "
     "В котором часу он прибыл?", 15),
    ("Студент решил 15 задач в понедельник, во вторник на 6 меньше, "
     "а в среду вдвое больше, чем во вторник. Сколько задач он решил за три дня?", 42),
]

DIRECT = "Реши задачу. Напиши только число, без объяснений."
STEP_BY_STEP = (
    "Реши задачу. Сначала рассуждай по шагам, записывая каждое действие. "
    "В последней строке напиши: Ответ: и число."
)


def last_number(answer):
    """Последнее число в тексте ответа или None."""
    numbers = re.findall(r"\d+", answer)
    return int(numbers[-1]) if numbers else None


def solve(system, max_new_tokens):
    correct = 0
    for question, right in tqdm(PUZZLES):
        # соберем диалог (system + вопрос), спросим модель,
        # достаньте из ответа последнее число и сравните с right
        answer = chat(
            [{"role": "system", "content": system}, {"role": "user", "content": question}],
            max_new_tokens=max_new_tokens,
        )
        correct += last_number(answer) == right
    return correct


n_direct = solve(DIRECT, max_new_tokens=12)
n_cot = solve(STEP_BY_STEP, max_new_tokens=220)
print(f"\nсразу ответ:        {n_direct} из {len(PUZZLES)}")
print(f"рассуждая по шагам: {n_cot} из {len(PUZZLES)}")

