
import re

import torch
import transformers
from tqdm import tqdm
from transformers import AutoTokenizer, AutoModelForCausalLM, pipeline

transformers.logging.set_verbosity_error()      # прячем предупреждения библиотеки

# Модель на 0.5 млрд параметров работает на любом ноутбуке, но часто ошибается.
# Если есть видеокарта или запас оперативной памяти, возьмите "Qwen/Qwen2.5-1.5B-Instruct".
MODEL_NAME = "Qwen/Qwen2.5-0.5B-Instruct"

tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
model = AutoModelForCausalLM.from_pretrained(MODEL_NAME)
model = model.float()       # на процессоре считаем в float32
model.eval()


# ---------------------------------------------------------------------------
# Часть 1. Шаблон чата
# ---------------------------------------------------------------------------
# Для модели диалог это один длинный текст. Роли размечены специальными токенами.

messages = [
    {"role": "system", "content": "Ты ассистент преподавателя. Отвечай коротко."},
    {"role": "user", "content": "Что такое токен?"},
]

prompt = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
print("--- так диалог выглядит для модели ---")
print(prompt)


def chat(messages, max_new_tokens=64):
    """Отправляет диалог в модель и возвращает только новый ответ ассистента."""
    # соберftv функцию из четырех шагов
    #   1) превраoftv messages в строку через tokenizer.apply_chat_template (как выше)
    #   2) токенизируем строку: tokenizer(prompt, return_tensors="pt")
    #   3) вызовем model.generate(**enc, max_new_tokens=..., do_sample=False)
    #   4) generate возвращает запрос вместе с ответом. Отрежаем токены запроса
    #      и декодируем остаток с skip_special_tokens=True
    prompt = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    enc = tokenizer(prompt, return_tensors="pt")
    with torch.no_grad():
        out = model.generate(**enc, max_new_tokens=max_new_tokens, do_sample=False)
    new_ids = out[0, enc["input_ids"].shape[1]:]
    return tokenizer.decode(new_ids, skip_special_tokens=True).strip()


print("--- ответ модели ---")
print(chat(messages))

# То же самое через готовый pipeline из библиотеки: он сам применяет шаблон чата.
pipe = pipeline("text-generation", model=model, tokenizer=tokenizer)
result = pipe(messages, max_new_tokens=64, do_sample=False)
print("--- ответ через pipeline ---")
print(result[0]["generated_text"][-1]["content"])


# ---------------------------------------------------------------------------
# Часть 2. Zero-shot против few-shot
# ---------------------------------------------------------------------------
# Задача: по сообщению студента определить, что это.
# Размеченных данных для обучения у нас нет. Есть только промпт.

LABELS = ["отмазка", "вопрос", "жалоба", "благодарность"]

DATA = [
    ("Я не сдал домашку, потому что кот лег на клавиатуру и отказался уходить.", "отмазка"),
    ("Интернет отключили ровно в тот момент, когда я нажимал кнопку отправить.", "отмазка"),
    ("Мой ноутбук решил обновиться и обновляется уже третий день.", "отмазка"),
    ("Я все сделал, но файл куда-то сам удалился, честное слово.", "отмазка"),
    ("Подскажите, почему у меня loss становится nan после первой эпохи?", "вопрос"),
    ("Можно ли в проекте использовать предобученную модель?", "вопрос"),
    ("До какого числа нужно сдать третье домашнее задание?", "вопрос"),
    ("Чем отличается LSTM от GRU, если коротко?", "вопрос"),
    ("В аудитории опять не работает проектор, с задних рядов ничего не видно.", "жалоба"),
    ("Домашние задания слишком большие, мы не успеваем по другим предметам.", "жалоба"),
    ("Пары поставили на восемь утра в субботу, это невозможно.", "жалоба"),
    ("В чате курса столько сообщений, что важные объявления теряются.", "жалоба"),
    ("Спасибо за лекцию про трансформеры, наконец-то стало понятно.", "благодарность"),
    ("Благодарю за подробные комментарии к моему проекту.", "благодарность"),
    ("Очень понравился семинар, особенно задача с пословицами.", "благодарность"),
    ("Спасибо, что перенесли дедлайн, это очень выручило.", "благодарность"),
]

# примеры для few-shot, в DATA их нет
EXAMPLES = [
    ("Я опоздал, потому что лифт застрял между этажами вместе со мной.", "отмазка"),
    ("Какой учебник вы посоветуете по линейной алгебре?", "вопрос"),
    ("На семинаре было так шумно, что я не слышал объяснений.", "жалоба"),
    ("Спасибо за интересный курс!", "благодарность"),
]

SYSTEM = (
    "Ты классифицируешь сообщения студентов преподавателю. "
    "Категории: отмазка, вопрос, жалоба, благодарность. "
    "Отвечай одним словом: названием категории."
)


def zero_shot(text):
    # диалог из двух сообщений: системное с инструкцией и сообщение студента
    return [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content": text},
    ]


def few_shot(text):
    # то же самое, но перед сообщением студента вставьте примеры из EXAMPLES.
    # Каждый пример это пара реплик: user с текстом и assistant с правильной категорией.
    # Модель увидит "историю диалога", в которой она уже четыре раза ответила правильно.
    messages = [{"role": "system", "content": SYSTEM}]
    for example_text, example_label in EXAMPLES:
        messages.append({"role": "user", "content": example_text})
        messages.append({"role": "assistant", "content": example_label})
    messages.append({"role": "user", "content": text})
    return messages


def parse_label(answer):
    """Достает категорию из ответа модели. Если категории нет, возвращает None."""
    # Модель может ответить "Отмазка.", "это жалоба" или "благодарности",
    # поэтому ищем по началу слова, а не точное совпадение.
    stems = {"отмаз": "отмазка", "вопрос": "вопрос", "жалоб": "жалоба", "благодар": "благодарность"}
    answer = answer.lower()
    for stem, label in stems.items():
        if stem in answer:
            return label
    return None


def evaluate(build_messages):
    """Доля правильных ответов на DATA для выбранного способа построить промпт."""
    correct = 0
    for text, label in tqdm(DATA):
        # спросиvм модель и сравним ответ с правильной категорией
        answer = chat(build_messages(text), max_new_tokens=8)
        correct += parse_label(answer) == label
    return correct / len(DATA)


acc_zero = evaluate(zero_shot)
acc_few = evaluate(few_shot)
print(f"\nточность zero-shot: {acc_zero:.2f}")
print(f"точность few-shot:  {acc_few:.2f}")


